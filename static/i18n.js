let UILANG = "zh";
function t(key, ...args) {
  let s = (I18N[UILANG] && I18N[UILANG][key]) || I18N.es[key] || key;
  args.forEach((a, i) => { s = s.replaceAll("{"+ i + "}", a); });
  return s;
}
function applyI18n(root = document) {
  root.querySelectorAll("[data-i18n]").forEach((el) => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll("[data-i18n-ph]").forEach((el) => { el.placeholder = t(el.dataset.i18nPh); });
  root.querySelectorAll("[data-i18n-title]").forEach((el) => { el.title = t(el.dataset.i18nTitle); if (el.hasAttribute("aria-label")) el.setAttribute("aria-label", el.title); });
  // placeholder de contenteditable (CSS :empty::before con attr(data-ph))
  root.querySelectorAll("[data-i18n-dph]").forEach((el) => { el.dataset.ph = t(el.dataset.i18nDph); });
}
// "auto" (por defecto en instalaciones nuevas) resuelve contra el idioma del
// navegador: el README está en inglés, así que quien llega de fuera no debería
// encontrarse la interfaz en español sin saber que hay selector.
function detectUILang() {
  for (const tag of navigator.languages || [navigator.language || ""]) {
    const base = String(tag).toLowerCase().split("-")[0];
    if (I18N[base]) return base;
  }
  return "en";
}
function setUILang(lang) {
  const want = lang === "auto" ? detectUILang() : lang;
  UILANG = I18N[want] ? want : "zh";
  document.documentElement.lang = UILANG;
  applyI18n();
}

// Render the default edition language before the settings request finishes.
setUILang("zh");
